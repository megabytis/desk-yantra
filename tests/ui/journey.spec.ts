import {test, expect} from '@playwright/test';
import {readFileSync, mkdtempSync, writeFileSync, existsSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';

const temporaryRoots:string[]=[];
test.afterEach(()=>{for(const root of temporaryRoots.splice(0))rmSync(root,{recursive:true,force:true});});

test('fixture: UI connection, model discovery, real host edit and artifact', async ({page}) => {
  const root = mkdtempSync(join(tmpdir(),'paw-project-'));
  temporaryRoots.push(root);
  const agentName = 'Fixture engineer ' + Date.now();
  execFileSync('git',['init',root]);
  writeFileSync(join(root,'maths.py'),'def add(left, right):\n    return left - right\n');
  writeFileSync(join(root,'test_math.py'),'import unittest\nfrom maths import add\nclass TestMath(unittest.TestCase):\n    def test_add(self):\n        self.assertEqual(add(2, 3), 5)\n');
  await page.addInitScript(()=>sessionStorage.setItem('paw.showTestData','true'));
  await page.goto('/');
  await page.getByLabel('Launch token').fill(readFileSync(join(process.env.PAW_STATE || '.state','token'),'utf8').trim());
  await page.getByRole('button',{name:'Connect to workbench'}).click();
  await page.getByRole('button',{name:/Settings & providers/}).click();
  await page.getByRole('button',{name:/Add connection/}).click();
  await page.getByLabel('Name',{exact:true}).fill('Fixture Ollama');
  await page.getByLabel('Base URL').fill('http://127.0.0.1:18767');
  await page.getByRole('button',{name:'Save connection'}).click();
  await page.getByRole('button',{name:'Refresh models'}).click();
  await expect(page.getByText('Last model refresh passed')).toBeVisible();
  await page.getByRole('combobox',{name:'Model',exact:true}).selectOption('fixture-tool-model');
  await page.getByRole('button',{name:'Test inference'}).click();
  await expect(page.getByRole('status')).toContainText('Inference succeeded',{timeout:45000});
  await expect(page.getByText('Last inference check passed')).toBeVisible();
  await page.getByRole('button',{name:'Use as default'}).click();
  await page.getByRole('button',{name:'Computer access',exact:true}).click();
  await page.getByRole('button',{name:/Add workspace/}).click();
  await page.getByRole('button',{name:/This computer/}).click();
  await page.getByLabel('Project folder').fill(root);
  await page.getByLabel('files',{exact:true}).check();
  await page.getByLabel('shell',{exact:true}).check();
  await page.getByRole('button',{name:'Save workspace'}).click();
  await expect(page.getByRole('heading',{name:root,exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Agents',exact:true}).click();
  await page.getByRole('button',{name:/Create agent/}).first().click();
  await page.getByLabel('Name',{exact:true}).fill(agentName);
  await page.getByLabel('files',{exact:true}).check();
  await page.getByLabel('shell',{exact:true}).check();
  await page.getByLabel(`host · ${root}`,{exact:true}).check();
  await page.getByRole('button',{name:'Save agent'}).click();
  await expect(page.getByRole('heading',{name:agentName})).toBeVisible();
  await page.getByRole('button',{name:/Back to conversation/}).click();
  await page.getByRole('button',{name:`Start a conversation with ${agentName}`}).click();
  await expect(page.getByRole('combobox',{name:'Agent',exact:true})).toHaveValue(/.+/);
  await expect(page.getByRole('combobox',{name:'Workspace',exact:true})).toHaveValue(/.+/);
  await page.getByRole('combobox',{name:'Agent',exact:true}).selectOption({label:agentName});
  await page.getByRole('combobox',{name:'Workspace',exact:true}).selectOption({label:`host · ${root}`});
  await page.getByLabel('Message',{exact:true}).fill('FIX_TEST: diagnose and fix the failing test');
  const created = page.waitForResponse(response => response.url().endsWith('/api/runs') && response.request().method() === 'POST');
  await page.getByRole('button',{name:'Start task'}).click();
  const run = await (await created).json();
  await page.getByRole('button',{name:'Approve this action',exact:true}).click({timeout:45000});
  await expect(page.locator('.inline-approval pre')).toContainText('return left + right',{timeout:45000});
  await page.getByRole('button',{name:'Approve this action',exact:true}).click();
  await expect(page.locator('.inline-approval h3')).toContainText('shell',{timeout:45000});
  await page.getByRole('button',{name:'Approve this action',exact:true}).click({timeout:45000});
  await expect(page.locator('.execution-pill')).toContainText('completed',{timeout:45000});
  await expect(page.getByRole('alert').filter({hasText:'Result needs your review'})).toContainText('A command passed after a file write');
  expect(readFileSync(join(root,'maths.py'),'utf8')).toContain('return left + right');
  execFileSync('python',['-m','unittest','test_math.py'],{cwd:root});
  await page.getByRole('button',{name:'Files',exact:true}).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link',{name:/maths.py/}).click();
  const download = await downloadPromise;
  expect(readFileSync((await download.path())!,'utf8')).toContain('return left + right');
  await page.evaluate(()=>{localStorage.setItem('paw.showTestData','true');sessionStorage.removeItem('paw.showTestData');});
  await page.reload();
  await page.getByRole('button',{name:'Agents',exact:true}).click();
  await expect(page.getByRole('heading',{name:agentName})).toHaveCount(0);
  await page.getByLabel('Show test records').check();
  await expect(page.getByRole('heading',{name:agentName})).toBeVisible();
});
