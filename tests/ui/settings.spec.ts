import {join} from 'node:path';
import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';

test('settings: edit connections without returning keys and edit agent instructions',async({page})=>{
  await page.addInitScript(()=>localStorage.setItem('paw.showTestData','true'));
  await page.goto('/');
  await page.getByLabel('Launch token').fill(readFileSync(join(process.env.PAW_STATE || '.state','token'),'utf8').trim());
  await page.getByRole('button',{name:'Connect to workbench'}).click();
  await page.getByRole('button',{name:/Settings & providers/}).click();
  await page.getByRole('button',{name:/Add connection/}).click();
  const name='Fixture editable connection '+Date.now();
  const secret='fixture-only-private-key-'+Date.now();
  await page.getByLabel('Name',{exact:true}).fill(name);
  await page.getByRole('combobox',{name:'Provider',exact:true}).selectOption('compatible');
  await page.getByLabel('Base URL').fill('http://127.0.0.1:18767/v1');
  await page.getByLabel('API key',{exact:true}).fill(secret);
  const saved=page.waitForResponse(response=>response.url().endsWith('/api/providers')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'Save connection',exact:true}).click();
  const provider=await(await saved).json();
  expect(provider.has_key).toBe(true);
  expect(provider.secret).toBeUndefined();
  expect(JSON.stringify(provider)).not.toContain(secret);
  await page.getByRole('button',{name:/Refresh models/}).click();
  await page.getByRole('combobox',{name:'Model',exact:true}).selectOption('fixture-tool-model');
  await page.getByRole('button',{name:'Edit connection',exact:true}).click();
  await expect(page.getByLabel('API key',{exact:true})).toHaveValue('');
  await page.getByLabel('Name',{exact:true}).fill(name+' renamed');
  await page.getByRole('button',{name:'Save connection',exact:true}).click();
  await expect(page.locator('.connection-card').filter({hasText:name+' renamed'})).toBeVisible();
  const state=await page.evaluate(()=>fetch('/api/state').then(response=>response.json()));
  const updated=state.providers.find((item:any)=>item.id===provider.id);
  expect(updated.has_key).toBe(true);
  expect(updated.models).toHaveLength(2);
  expect(JSON.stringify(state)).not.toContain(secret);
  await page.getByRole('button',{name:'Agents',exact:true}).click();
  await page.getByRole('button',{name:/Create agent/}).first().click();
  const agentName='Fixture editable agent '+Date.now();
  await page.getByLabel('Name',{exact:true}).fill(agentName);
  await page.getByRole('textbox',{name:'Instructions',exact:true}).fill('Initial instructions');
  await page.getByRole('combobox',{name:'Connection',exact:true}).selectOption(provider.id);
  await page.getByRole('combobox',{name:'Model',exact:true}).selectOption('fixture-tool-model');
  await page.getByRole('button',{name:'Save agent',exact:true}).click();
  const card=page.locator('.profile-card').filter({hasText:agentName});
  await card.getByRole('button',{name:'Edit agent',exact:true}).click();
  await page.getByRole('textbox',{name:'Instructions',exact:true}).fill('Updated instructions preserved after reload');
  await page.getByRole('combobox',{name:'Model',exact:true}).selectOption('fixture-second-model');
  await page.getByRole('button',{name:'Save agent',exact:true}).click();
  await page.reload();
  await expect(card).toContainText('Updated instructions preserved after reload');
  await expect(card).toContainText('fixture-second-model');
  await card.getByRole('button',{name:'Archive agent',exact:true}).click();
  await expect(card).toHaveCount(0);
  await page.getByLabel('Show archived agents',{exact:true}).check();
  await expect(card).toContainText('Archived');
  await card.getByRole('button',{name:'Restore agent',exact:true}).click();
  await expect(card).not.toContainText('Archived');
  await page.getByRole('button',{name:'Providers & models',exact:true}).click();
  await page.locator('.connection-card').filter({hasText:name+' renamed'}).click();
  await page.getByRole('button',{name:'Archive connection',exact:true}).click();
  await page.getByLabel('Show archived connections',{exact:true}).check();
  await page.locator('.connection-card').filter({hasText:name+' renamed'}).click();
  await page.getByRole('button',{name:'Restore connection',exact:true}).click();
  const restored=await page.evaluate(()=>fetch('/api/state').then(response=>response.json()));
  expect(restored.providers.find((item:any)=>item.id===provider.id).has_key).toBe(true);
  expect(restored.runs).toEqual(state.runs);
  await page.getByRole('button',{name:'Edit connection',exact:true}).click();
  await page.getByLabel('Remove saved API key from this connection').check();
  await page.getByRole('button',{name:'Save connection',exact:true}).click();
  await page.reload();
  await expect(page.locator('.connection-card').filter({hasText:name+' renamed'})).toContainText('No API key');
  const afterRemoval=await page.evaluate(()=>fetch('/api/state').then(response=>response.json()));
  expect(afterRemoval.providers.find((item:any)=>item.id===provider.id).has_key).toBe(false);
  expect(afterRemoval.runs).toEqual(state.runs);
});

test('settings: failed model refresh keeps existing models and explains the failure',async({page})=>{
  await page.addInitScript(()=>localStorage.setItem('paw.showTestData','true'));
  await page.goto('/');
  await page.getByLabel('Launch token').fill(readFileSync(join(process.env.PAW_STATE || '.state','token'),'utf8').trim());
  await page.getByRole('button',{name:'Connect to workbench'}).click();
  await page.getByRole('button',{name:/Settings & providers/}).click();
  await page.getByRole('button',{name:/Add connection/}).click();
  const name='Fixture failing refresh '+Date.now();
  await page.getByLabel('Name',{exact:true}).fill(name);
  await page.getByRole('combobox',{name:'Provider',exact:true}).selectOption('compatible');
  await page.getByLabel('Base URL').fill('http://127.0.0.1:1/v1');
  await page.getByRole('button',{name:'Save connection',exact:true}).click();
  await page.getByRole('button',{name:'Refresh models'}).click();
  await expect(page.getByText('Last model refresh failed')).toBeVisible();
  await expect(page.locator('.connection-check.check-failed')).toContainText('Server unreachable');
  await page.reload();
  await page.locator('.connection-card').filter({hasText:name}).click();
  await expect(page.getByText('Last model refresh failed')).toBeVisible();
});
