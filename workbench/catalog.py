def get_catalog():
    """Return the complete model catalog indexed by provider type."""
    return CATALOG


def catalog_for_provider(provider_type: str):
    """Return list of recommended/catalog models for a given provider type."""
    return CATALOG.get(provider_type, [])


def find_catalog_model(provider_type: str, model_id: str):
    """Lookup a specific catalog entry by provider type and model id."""
    for model in CATALOG.get(provider_type, []):
        if model["id"] == model_id:
            return model
    return None

